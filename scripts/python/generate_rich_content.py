#!/usr/bin/env python3
"""Generate rich workplace English exercise modules."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODULES = ROOT / "content" / "modules"
MANIFEST = ROOT / "content" / "manifest.json"

TTS = {"scenario": True, "prompt": True, "answer": True}


def mk(
    module_id: str,
    prefix: str,
    idx: int,
    difficulty: str,
    scenario: str,
    prompt: str,
    choices: list[str],
    correct: str,
    explanation: str,
    tags: list[str],
) -> dict:
    return {
        "id": f"{prefix}-{idx:02d}",
        "moduleId": module_id,
        "difficulty": difficulty,
        "scenario": scenario,
        "prompt": prompt,
        "choices": [
            {"key": k, "text": t} for k, t in zip(["A", "B", "C", "D"], choices)
        ],
        "correctKey": correct,
        "explanation": explanation,
        "tags": tags,
        "tts": TTS,
    }


def pack(
    module_id: str,
    title: str,
    description: str,
    persona: list[str],
    items: list[dict],
) -> dict:
    return {
        "id": module_id,
        "title": title,
        "description": description,
        "persona": persona,
        "status": "ready",
        "itemCount": len(items),
        "items": items,
    }


def write_module(data: dict) -> None:
    path = MODULES / f"{data['id']}.json"
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.name}: {data['itemCount']} items")


