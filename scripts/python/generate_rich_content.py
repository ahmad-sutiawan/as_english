def append_extras(module_id: str, extras: list[dict]) -> None:
    path = MODULES / f"{module_id}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    existing_ids = {i["id"] for i in data["items"]}
    for item in extras:
        if item["id"] not in existing_ids:
            data["items"].append(item)
    data["status"] = "ready"
    data["itemCount"] = len(data["items"])
    write_module(data)


def update_manifest() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for meta in manifest["modules"]:
        path = MODULES / f"{meta['id']}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        meta["status"] = data["status"]
        meta["itemCount"] = data["itemCount"]
        meta["description"] = data["description"]
        meta["title"] = data["title"]
        meta["persona"] = data["persona"]
    manifest["version"] = "1.1.0"
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("updated manifest.json")


