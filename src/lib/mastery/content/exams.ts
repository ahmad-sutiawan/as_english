import type { ExamDef, ExamQuestion } from "@/types/mastery";

function q(
  examId: string,
  index: number,
  lessonId: string,
  draft: Omit<ExamQuestion, "id" | "lessonId" | "points" | "difficulty"> & {
    difficulty?: ExamQuestion["difficulty"];
  },
): ExamQuestion {
  return {
    points: 1,
    difficulty: draft.difficulty ?? "core",
    ...draft,
    id: `${examId}-q${index}`,
    lessonId,
  };
}

